def main() -> None:
    parser = _build_parser()
    args = parser.parse_args()

    datasets = list(dict.fromkeys(args.datasets))
    models = args.models or list(DEFAULT_SMALL_MODELS)

    _validate_models(models)
    _validate_models([args.judge_model])

    data_paths: dict[str, str | None] = {
        "wisdm": args.wisdm_data,
        "mit_ecg": args.mit_ecg_data,
        "bus": args.bus_data,
    }
    gt_paths: dict[str, str | None] = {
        "wisdm": args.wisdm_gt,
        "mit_ecg": args.mit_ecg_gt,
        "bus": args.bus_gt,
    }

    run_id = _make_run_id(args.run_id)
    run_output_dir = _resolve_run_output_dir(args.output_dir, run_id)

    if args.dry_run_check_paths:
        print("Preflight checks")
        print(f"  Run id: {run_id}")
        print(f"  Run output directory: {run_output_dir}")
        print(f"  Models under test: {models}")
        print(f"  Judge model: {args.judge_model}")
        for dataset in datasets:
            ds_path = _resolve_dataset_file(dataset, data_paths.get(dataset))
            gt_path = _resolve_ground_truth_file(dataset, gt_paths.get(dataset))
            print(f"  {dataset}: data={ds_path}")
            print(f"  {dataset}: gt={gt_path}")
        print("Dry-run preflight complete.")
        return

    if args.plot_only:
        plot_results_from_runs(
            args.output_dir,
            benchmark_all_root=args.benchmark_data_root,
            benchmark_ecg_root=args.benchmark_ecg_root,
        )
        return

    if args.run_all:
        for run_num in (1, 2, 3):
            run_id_n = str(run_num)
            run_output_dir_n = _resolve_run_output_dir(args.output_dir, run_id_n)
            print(f"\n{'='*60}", flush=True)
            print(f"Starting run {run_num}/3  →  {run_output_dir_n}", flush=True)
            print(f"{'='*60}", flush=True)
            q_df, s_df = run_experiment(
                datasets=datasets,
                models=models,
                query_ids=args.query_ids,
                data_paths=data_paths,
                gt_paths=gt_paths,
                run_output_dir=str(run_output_dir_n),
                judge_model=args.judge_model,
                run_id=run_output_dir_n.name,
            )
            print(f"Run {run_num} complete — {len(q_df)} query rows, {len(s_df)} summary rows.", flush=True)
        print("\nAll 3 runs complete. Generating figure…", flush=True)
        plot_results_from_runs(
            args.output_dir,
            benchmark_all_root=args.benchmark_data_root,
            benchmark_ecg_root=args.benchmark_ecg_root,
        )
        return

    query_metrics_df, summary_df = run_experiment(
        datasets=datasets,
        models=models,
        query_ids=args.query_ids,
        data_paths=data_paths,
        gt_paths=gt_paths,
        run_output_dir=str(run_output_dir),
        judge_model=args.judge_model,
        run_id=run_output_dir.name,
    )

    print(f"Saved per-query rows: {len(query_metrics_df)}")
    print(f"Saved summary rows: {len(summary_df)}")
    print(f"Run output directory: {run_output_dir}")
    print(f"Summary CSV: {run_output_dir / 'modeltype_summary.csv'}")

    if args.plot:
        plot_results_from_runs(
            args.output_dir,
            benchmark_all_root=args.benchmark_data_root,
            benchmark_ecg_root=args.benchmark_ecg_root,
        )


if __name__ == "__main__":
    main()